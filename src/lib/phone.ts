// بيوحّد شكل رقم الهاتف المصري لصيغة واحدة (01xxxxxxxxx) بغض النظر عن الشكل اللي اتكتب بيه
// (بمفتاح دولي +20 أو 0020 أو من غير الصفر الأول) - عشان نفس العميل ميتسجلش مرتين بصيغتين مختلفتين.
export function normalizePhone(raw: string): string {
  let p = (raw || "").trim().replace(/[\s-]/g, "");
  if (!p) return p;
  if (p.startsWith("+20")) p = p.slice(3);
  else if (p.startsWith("0020")) p = p.slice(4);
  else if (p.startsWith("20") && p.length === 12) p = p.slice(2);
  else return p; // مفيش مفتاح دولي - رقم محلي عادي (يبدأ بـ 0 أو غيره)، سيبه زي ما هو من غير أي لمس

  // بعد شيل المفتاح الدولي، الجزء المتبقي أحيانًا بيكون لسه فيه صفر بادئ (غلطة إدخال شائعة - حد
  // بيكتب "+2001012345678" محتفظ بالصفر المحلي بعد ما ضاف +20 بالغلط). قبل كده كان بيتحط "0" جديد
  // فوق الصفر ده من غير ما يشيله الأول، فينتج رقم بـ12 رقم (بدل 11) زي "001012345678" - رقم مش
  // مطابق لنفس العميل لو دخل بصيغة صح من قناة تانية، فبيتسجل عميل مكرر بالغلط.
  p = p.replace(/^0+/, "");
  return "0" + p;
}
